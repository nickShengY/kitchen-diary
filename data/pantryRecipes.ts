import { Recipe, RecipeStep, RecipeStepSettings } from '../types';
import { ACTIONS, INGREDIENTS, TOOLS } from './kitchenData';

/**
 * The pantry corpus powers "cook what you already have".
 *
 * Every id below is a real entry in the shared ingredient / tool / action
 * catalogue, so a matched dish can be opened in the builder and played back
 * with the generated artwork instead of a placeholder.
 */

export type Course = 'main' | 'side' | 'soup' | 'breakfast' | 'dessert' | 'snack';

export interface PantryStepSpec {
  /** Action id from ACTIONS. */
  a: string;
  /** Ingredient ids used by this step. */
  i?: string[];
  /** Tool override; defaults to the action's canonical tool. */
  t?: string;
  s?: RecipeStepSettings;
  /** Plain-language instruction shown in the recipe sheet. */
  n: string;
}

export interface PantryRecipe {
  id: string;
  title: string;
  emoji: string;
  blurb: string;
  cuisine: string;
  course: Course;
  tags: string[];
  minutes: number;
  servings: number;
  /** 1 = anyone can do it, 3 = a weekend project. */
  difficulty: 1 | 2 | 3;
  /** Ingredients that define the dish. Missing one means a shopping trip. */
  core: string[];
  /** Nice-to-have ingredients the dish is still recognisable without. */
  extras?: string[];
  /** Cookware the dish cannot be made without. */
  tools: string[];
  steps: PantryStepSpec[];
}

