// --------------------------------------------------------------- conversions

const ingredientById = new Map(INGREDIENTS.map((item) => [item.id, item]));
const actionById = new Map(ACTIONS.map((item) => [item.id, item]));
const toolById = new Map(TOOLS.map((item) => [item.id, item]));

const stationForTool = (toolId: string): RecipeStep['station'] => {
  const tool = toolById.get(toolId);
  if (!tool) return 'finish';
  if (tool.type === 'prep') return 'prep';
  if (tool.type === 'finish') return 'finish';
  return 'cook';
};

const stepIngredients = (ids: string[] | undefined) =>
  (ids ?? [])
    .filter((id) => ingredientById.has(id))
    .map((id) => ({
      id,
      amount: '1',
      unit: ingredientById.get(id)?.defaultUnit ?? 'pcs',
    }));

/** Finishing actions carry no tool in the catalogue; they all happen on the plate. */
const FINISHING_ACTIONS = new Set(['plate', 'garnish', 'drizzle', 'sprinkle']);

/**
 * Picks the tool a step should show in the builder. Explicit wins, then the
 * dish's own cookware when it can do the job (a wok recipe should say "wok",
 * not the catalogue's generic pan), then the action's canonical tool.
 */
const toolForStep = (recipe: PantryRecipe, spec: PantryStepSpec): string => {
  if (spec.t) return spec.t;

  const action = actionById.get(spec.a);
  const canonical = action?.requiresToolId;

  if (canonical && !recipe.tools.includes(canonical)) {
    const declared = recipe.tools.find((id) => {
      const type = toolById.get(id)?.type;
      return action?.requiresHeat ? type === 'cook' || type === 'appliance' : false;
    });
    if (declared) return declared;
  }

  if (canonical) return canonical;
  return FINISHING_ACTIONS.has(spec.a) ? 'plate' : 'bowl';
};

export const pantryRecipeToRecipeSteps = (recipe: PantryRecipe): RecipeStep[] =>
  recipe.steps.map((spec, index) => {
    const toolId = toolForStep(recipe, spec);
    return {
      id: `${recipe.id}-step-${index}`,
      station: stationForTool(toolId),
      ingredients: stepIngredients(spec.i),
      toolId,
      actionId: spec.a,
      settings: spec.s,
      notes: spec.n,
    } satisfies RecipeStep;
  });

/** Every ingredient the corpus can actually match on, in catalogue order. */
export const CORPUS_INGREDIENT_IDS: string[] = (() => {
  const ids = new Set<string>();
  PANTRY_RECIPES.forEach((recipe) => {
    recipe.core.forEach((id) => ids.add(id));
    (recipe.extras ?? []).forEach((id) => ids.add(id));
  });
  return INGREDIENTS.filter((item) => ids.has(item.id)).map((item) => item.id);
})();

export const pantryRecipeToRecipe = (recipe: PantryRecipe): Recipe => ({
  id: `pantry-${recipe.id}`,
  title: recipe.title,
  description: recipe.blurb,
  authorId: 'kitchendiary-kitchen',
  authorName: `${recipe.cuisine} Kitchen`,
  authorAvatar: recipe.emoji,
  steps: pantryRecipeToRecipeSteps(recipe),
  tags: recipe.tags,
  createdAt: 0,
});

